from datetime import date, datetime
from decimal import Decimal
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

from app.shared.types import Money, Quantity

EntryType = Literal["sale", "credit_sale", "payment_received", "expense"]


class ExtractedEntry(BaseModel):
    """What the ledger accepts from interpretation (the AI slice). Any field may be missing;
    the ledger decides in code whether it is complete enough to save (FR-S5)."""

    model_config = ConfigDict(str_strip_whitespace=True)

    type: EntryType | None = None
    item: str | None = Field(default=None, min_length=1, max_length=100)
    quantity: Decimal | None = Field(default=None, gt=0)
    unit: str | None = Field(default=None, min_length=1, max_length=40)
    amount_ngn: Decimal | None = Field(default=None, ge=0)
    customer: str | None = Field(default=None, min_length=1, max_length=120)
    due_date: date | None = None
    confidence: float | None = Field(default=None, ge=0, le=1)


class EntryOut(BaseModel):
    id: int
    type: EntryType
    item: str | None
    quantity: Quantity | None
    unit: str | None
    amount_ngn: Money
    customer: str | None
    due_date: date | None
    confidence: float | None
    status: str
    raw_text: str
    created_at: datetime
    updated_at: datetime


class MessageRequest(BaseModel):
    """A typed message from the app. client_message_id is generated by the app per message (NFR-5)."""

    model_config = ConfigDict(str_strip_whitespace=True)

    text: str = Field(min_length=1, max_length=2000)
    client_message_id: str = Field(min_length=1, max_length=64)


class LedgerResult(BaseModel):
    """Outcome of one message (FR-S1, S5, S6, S8): saved, corrected, one clarifying question,
    or a polite fallback for off-topic messages. `transcript` is set for voice notes (FR-S2)."""

    status: Literal["saved", "corrected", "clarify", "fallback"]
    message: str
    entry: EntryOut | None = None
    flags: list[Literal["not_in_inventory", "check_stock"]] = Field(default_factory=list)
    transcript: str | None = None
